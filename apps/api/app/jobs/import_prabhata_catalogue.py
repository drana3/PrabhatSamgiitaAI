"""Idempotent, resumable catalogue transliteration job (song IDs 1..5018).

Design decisions
----------------
* **Source of truth is the local authoritative dataset**
  (``data/generated/songs.json``), which already contains the extracted and
  verified Roman lyrics for all 5018 songs. We therefore do *not* re-scrape
  the website by default: that respects the site's terms, avoids fabricating
  data, and keeps provenance honest. The extraction step is still isolated in
  :func:`extract_songs` so a future HTTP source (with a proper HTML parser and
  bounded, polite concurrency) can be slotted in behind the same interface.
* **Devanagari is generated by the deterministic rule-based engine** and is
  always marked ``devanagari_origin = "rule_based"`` and
  ``verification_status`` taken from the independent verifier. No record is
  claimed as authoritative or manually verified unless it already is.
* **Manually verified / reference-matched records are never overwritten.**

CLI::

    python -m app.jobs.import_prabhata_catalogue --dry-run
    python -m app.jobs.import_prabhata_catalogue --resume
    python -m app.jobs.import_prabhata_catalogue --export-json
    python -m app.jobs.import_prabhata_catalogue --validate-export
    python -m app.jobs.import_prabhata_catalogue --report
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import logging
from collections import Counter
from pathlib import Path
from typing import Any

from app.services.transliteration import (
    ENGINE_VERSION,
    RULESET_VERSION,
    transliterate,
    verify,
)

logger = logging.getLogger("import_prabhata_catalogue")

SCHEMA_VERSION = "1.0.0"
CATALOGUE_NAME = "Prabhata Samgiita"
PRESERVE_STATUSES = {"manually_verified", "reference_matched"}

# --- Paths -----------------------------------------------------------------
_API_ROOT = Path(__file__).resolve().parents[2]  # apps/api
_REPO_ROOT = Path(__file__).resolve().parents[4]  # repo root
_DATA = _REPO_ROOT / "data" / "generated"
SOURCE_JSON = _DATA / "songs.json"
EXPORT_JSON = _DATA / "transliteration_catalogue.json"
STATE_JSON = _DATA / "transliteration_catalogue.state.json"
REPORT_JSON = _DATA / "transliteration_catalogue.report.json"
SCHEMA_PATH = _REPO_ROOT / "data" / "schemas" / "transliteration_catalogue.schema.json"
CONTENT_SOURCE = "https://prabhatasamgiita.net"


# ---------------------------------------------------------------------------
# Extraction (local authoritative dataset)
# ---------------------------------------------------------------------------
def extract_songs() -> list[dict[str, Any]]:
    """Load the authoritative Roman lyrics for every song.

    Returns a list of normalized dicts: ``{number, title, roman_text,
    roman_source_url}``. Never fabricates a missing song.
    """
    raw = json.loads(SOURCE_JSON.read_text(encoding="utf-8"))
    songs: list[dict[str, Any]] = []
    seen: set[int] = set()
    for entry in raw:
        number = entry.get("number")
        if not isinstance(number, int) or number in seen:
            continue
        seen.add(number)
        roman = (entry.get("lyrics_original") or "").strip("\n")
        rel = entry.get("canonical_source_url")
        url = f"{CONTENT_SOURCE}{rel}" if rel and rel.startswith("/") else rel
        songs.append(
            {
                "number": number,
                "title": entry.get("title"),
                "roman_text": roman,
                "roman_source_url": url,
            }
        )
    songs.sort(key=lambda s: s["number"])
    return songs


def _hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Per-song transliteration → canonical record
# ---------------------------------------------------------------------------
def build_song_record(song: dict[str, Any]) -> dict[str, Any]:
    roman_text: str = song["roman_text"]
    roman_lines = roman_text.split("\n") if roman_text else []

    dev_lines: list[str | None] = []
    line_pairs: list[dict[str, Any]] = []
    statuses: list[str] = []

    for idx, line in enumerate(roman_lines, start=1):
        if line.strip() == "":
            dev_lines.append(line)  # preserve stanza / blank boundaries verbatim
            line_pairs.append(
                {"line_number": idx, "roman": line, "devanagari": line, "status": "rules_passed"}
            )
            continue
        result = transliterate(line)
        report = verify(result)
        dev_lines.append(result.devanagari)
        line_pairs.append(
            {
                "line_number": idx,
                "roman": line,
                "devanagari": result.devanagari,
                "status": report.status.value,
            }
        )
        statuses.append(report.status.value)

    if any(s == "unsupported_input" for s in statuses):
        song_status = "unsupported_input"
    elif any(s == "needs_review" for s in statuses) or not statuses:
        song_status = "needs_review"
    else:
        song_status = "rules_passed"

    dev_text = "\n".join("" if d is None else d for d in dev_lines) if roman_lines else None

    return {
        "song_number": song["number"],
        "title": song.get("title"),
        "roman": {"text": roman_text, "lines": roman_lines},
        "devanagari": {"text": dev_text, "lines": dev_lines},
        "line_pairs": line_pairs,
        "provenance": {
            "roman_source_url": song.get("roman_source_url"),
            "devanagari_source_url": None,
            "devanagari_origin": "rule_based",
            "ruleset_version": RULESET_VERSION,
            "engine_version": ENGINE_VERSION,
            "roman_source_hash": _hash(roman_text),
            "verification_status": song_status,
            "verified_by": None,
            "verified_at": None,
        },
    }


# ---------------------------------------------------------------------------
# State / resume handling
# ---------------------------------------------------------------------------
def _load_state() -> dict[str, Any]:
    if STATE_JSON.exists():
        data: dict[str, Any] = json.loads(STATE_JSON.read_text(encoding="utf-8"))
        return data
    return {"completed": {}}  # number(str) -> roman_source_hash


def _save_state(state: dict[str, Any]) -> None:
    STATE_JSON.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")


def _load_existing_export() -> dict[int, dict[str, Any]]:
    if not EXPORT_JSON.exists():
        return {}
    data = json.loads(EXPORT_JSON.read_text(encoding="utf-8"))
    return {s["song_number"]: s for s in data.get("songs", [])}


def _is_protected(record: dict[str, Any]) -> bool:
    prov = record.get("provenance", {})
    return (
        prov.get("verification_status") in PRESERVE_STATUSES
        or prov.get("devanagari_origin") in {"authoritative", "manually_verified"}
        or bool(prov.get("verified_by"))
    )


# ---------------------------------------------------------------------------
# Core run
# ---------------------------------------------------------------------------
def run(dry_run: bool = False, resume: bool = False) -> dict[str, Any]:
    songs = extract_songs()
    existing = _load_existing_export()
    state = _load_state() if resume else {"completed": {}}
    completed: dict[str, str] = state.get("completed", {})

    records: dict[int, dict[str, Any]] = dict(existing)
    processed = skipped_resume = preserved = 0

    for song in songs:
        number = song["number"]
        src_hash = _hash(song["roman_text"])

        prior = existing.get(number)
        if prior and _is_protected(prior):
            records[number] = prior
            preserved += 1
            continue

        if resume and completed.get(str(number)) == src_hash and prior is not None:
            skipped_resume += 1
            continue

        record = build_song_record(song)
        processed += 1
        if not dry_run:
            records[number] = record
            completed[str(number)] = src_hash

    ordered = [records[n] for n in sorted(records)]
    catalogue = {
        "schema_version": SCHEMA_VERSION,
        "catalogue": CATALOGUE_NAME,
        "generated_at": dt.datetime.now(dt.UTC).isoformat(),
        "ruleset_version": RULESET_VERSION,
        "engine_version": ENGINE_VERSION,
        "songs": ordered,
    }

    if not dry_run:
        EXPORT_JSON.write_text(
            json.dumps(catalogue, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        state["completed"] = completed
        _save_state(state)

    summary = {
        "songs_extracted": len(songs),
        "processed": processed,
        "skipped_resume": skipped_resume,
        "preserved_protected": preserved,
        "dry_run": dry_run,
    }
    logger.info("catalogue run complete: %s", summary)
    return {"summary": summary, "catalogue": catalogue}


# ---------------------------------------------------------------------------
# Validation (self-contained draft-07 subset; uses `jsonschema` if available)
# ---------------------------------------------------------------------------
_VALID_STATUS = {
    "rules_passed",
    "reference_matched",
    "needs_review",
    "unsupported_input",
    "manually_verified",
}


def validate_catalogue(data: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    try:  # Prefer a real validator when the dependency is present.
        import jsonschema  # type: ignore

        schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
        validator = jsonschema.Draft7Validator(schema)
        return [f"{'/'.join(map(str, e.path))}: {e.message}" for e in validator.iter_errors(data)]
    except ModuleNotFoundError:
        pass  # fall back to the built-in structural checks below

    for key in ("schema_version", "catalogue", "songs"):
        if key not in data:
            errors.append(f"missing top-level key: {key}")
    for song in data.get("songs", []):
        n = song.get("song_number")
        if not isinstance(n, int) or n < 1:
            errors.append(f"invalid song_number: {n!r}")
        for key in ("roman", "devanagari", "line_pairs", "provenance"):
            if key not in song:
                errors.append(f"song {n}: missing {key}")
        prov = song.get("provenance", {})
        if prov.get("verification_status") not in _VALID_STATUS:
            errors.append(
                f"song {n}: bad verification_status {prov.get('verification_status')!r}"
            )
        if prov.get("devanagari_origin") not in {
            "rule_based",
            "authoritative",
            "manually_verified",
        }:
            errors.append(
                f"song {n}: bad devanagari_origin {prov.get('devanagari_origin')!r}"
            )
        for lp in song.get("line_pairs", []):
            if lp.get("status") not in _VALID_STATUS:
                errors.append(f"song {n}: bad line status {lp.get('status')!r}")
    return errors


def validate_export() -> list[str]:
    if not EXPORT_JSON.exists():
        return [f"export not found: {EXPORT_JSON}"]
    data = json.loads(EXPORT_JSON.read_text(encoding="utf-8"))
    return validate_catalogue(data)


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def build_report(catalogue: dict[str, Any] | None = None) -> dict[str, Any]:
    if catalogue is None:
        if not EXPORT_JSON.exists():
            raise FileNotFoundError("run the export first (--export-json)")
        catalogue = json.loads(EXPORT_JSON.read_text(encoding="utf-8"))

    songs = catalogue.get("songs", [])
    status_counts: Counter[str] = Counter()
    line_status: Counter[str] = Counter()
    with_authoritative = 0
    expected_ids = set(range(1, 5019))
    present_ids = {s["song_number"] for s in songs}

    for s in songs:
        status_counts[s["provenance"]["verification_status"]] += 1
        if s["provenance"]["devanagari_origin"] in {"authoritative", "manually_verified"}:
            with_authoritative += 1
        for lp in s["line_pairs"]:
            line_status[lp["status"]] += 1

    total_lines = sum(line_status.values())
    report = {
        "generated_at": dt.datetime.now(dt.UTC).isoformat(),
        "ruleset_version": catalogue.get("ruleset_version"),
        "engine_version": catalogue.get("engine_version"),
        "songs_total": len(songs),
        "songs_with_authoritative_devanagari": with_authoritative,
        "songs_provisional_rule_based": len(songs) - with_authoritative,
        "songs_requiring_manual_review": status_counts.get("needs_review", 0)
        + status_counts.get("unsupported_input", 0),
        "song_status_counts": dict(status_counts),
        "line_status_counts": dict(line_status),
        "line_rules_passed_pct": round(
            100 * line_status.get("rules_passed", 0) / total_lines, 3
        )
        if total_lines
        else 0.0,
        "missing_song_ids": sorted(expected_ids - present_ids)[:50],
        "missing_song_count": len(expected_ids - present_ids),
        "duplicate_song_ids": [n for n, c in Counter(
            s["song_number"] for s in songs
        ).items() if c > 1],
    }
    return report


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    parser = argparse.ArgumentParser(description="Prabhata Samgiita catalogue transliteration job")
    parser.add_argument("--dry-run", action="store_true", help="process without writing")
    parser.add_argument("--resume", action="store_true", help="skip unchanged done songs")
    parser.add_argument("--export-json", action="store_true", help="write canonical JSON")
    parser.add_argument("--validate-export", action="store_true", help="validate vs schema")
    parser.add_argument("--report", action="store_true", help="write + print quality report")
    args = parser.parse_args(argv)

    if args.validate_export:
        errors = validate_export()
        if errors:
            print(f"INVALID export ({len(errors)} errors):")
            for e in errors[:50]:
                print("  -", e)
            return 1
        print("export is schema-valid")
        return 0

    if args.report and not (args.export_json or args.dry_run):
        report = build_report()
        REPORT_JSON.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0

    # Default behaviour (and --export-json / --dry-run / --resume) runs the job.
    outcome = run(dry_run=args.dry_run, resume=args.resume)
    print(json.dumps(outcome["summary"], ensure_ascii=False, indent=2))
    if args.report:
        report = build_report(outcome["catalogue"])
        if not args.dry_run:
            REPORT_JSON.write_text(
                json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
            )
        print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
