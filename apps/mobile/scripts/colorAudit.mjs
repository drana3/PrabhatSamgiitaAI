#!/usr/bin/env node
/**
 * Colour audit: finds hardcoded colours and risky text/background pairs in the app source.
 * Rules are in docs/ui-colour-system.md. Heuristic (line and style-block based), meant to point a
 * human at the right lines, not to replace the pair table test (__tests__/colorPairs.test.ts).
 *
 * usage: node scripts/colorAudit.mjs [outFile.md]    (default: prints markdown to stdout)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(fileURLToPath(import.meta.url), "..", "..")
const DIRS = ["app", "components", "lib", "hooks", "stores", "utils"]
const SKIP = /(^|\/)(node_modules|public|\.expo)(\/|$)/

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (SKIP.test(relative(root, p))) continue
    const st = statSync(p)
    if (st.isDirectory()) walk(p, out)
    else if (/\.(ts|tsx)$/.test(name)) out.push(p)
  }
  return out
}

const ORANGE_FILL = /backgroundColor:[^,}]*\b(orange[3-6]00|orange500|gold500|accentBright|logoSun|#F67931|#FB7122|#E5610F|#FB9A5A|amColors\.orange[3-6]00)\b/
const ORANGE_BG_OBJ = /\bbg:\s*[^,}]*\b(orange[3-6]00|gold500|#F67931|#FB7122|#E5610F)\b/
const DARK_TEXT = /\b(color|fg):\s*[^,}]*(\bink[89]00\b|textHeading|#1E1E1E|#333333|#333\b|\bonInk\b|theme\.ink900|\.ink800)/
const WHITE_TEXT = /\b(color|fg):\s*[^,}]*(amColors\.white|#FFFFFF|#FFF\b|"white"|onBrand)/i
// `theme.ink300` / `p.ink300` / `tone.ink300` are themed to headingSecond (4:1, large two-tone headings only): allowed.
// The raw amColors.ink300 / ink400 / ink200 and grey hex are not.
const GREY_TEXT = /(^|[\s{,])(color|fg):\s*[^,}]*(amColors\.ink[234]00\b|(?<!\.)\bink[24]00\b|#999\b|#999999|#B3B3B3|#CCCCCC|#CCC\b)/i
const COLOURED_BADGE_BG = /backgroundColor:[^,}]*\b(orange\d+|accentBright|brand|sage\d+|olive\d+|tintGreen|gold\d+|logoSun|oliveBg|peach|#F67931|#2C3A27|#3C5535)\b/
const BADGE_KEY = /^\s*(\w*(badge|chip|tag|label|pill|over|ribbon|stamp)\w*)\s*:\s*\{/i
const IMAGE_USE = /<(Image|ImageBackground|ExpoImage|Cover|KiirtanCover|SongCover|Photo)\b|expo-image|ImageBackground/
const HEX = /#[0-9A-Fa-f]{6}\b|#[0-9A-Fa-f]{3}\b/g

const sections = {
  grey: [],
  darkOnOrange: [],
  whiteOnOrange: [],
  badgeOnImage: [],
  hex: [],
}

const files = DIRS.flatMap((d) => {
  try {
    return walk(join(root, d))
  } catch {
    return []
  }
}).sort()

for (const file of files) {
  const rel = relative(root, file)
  const lines = readFileSync(file, "utf8").split("\n")
  const hasImage = lines.some((l) => IMAGE_USE.test(l))
  lines.forEach((line, i) => {
    const n = i + 1
    const t = line.trim()
    if (t.startsWith("//") || t.startsWith("*") || t.startsWith("/*")) return
    if (GREY_TEXT.test(line)) sections.grey.push(`${rel}:${n}  ${t.slice(0, 140)}`)
    const orangeHere = ORANGE_FILL.test(line) || ORANGE_BG_OBJ.test(line)
    if (orangeHere) {
      const near = lines.slice(Math.max(0, i - 6), i + 7)
      const dark = near.find((l) => DARK_TEXT.test(l))
      const white = near.find((l) => WHITE_TEXT.test(l))
      if (dark) sections.darkOnOrange.push(`${rel}:${n}  bg ${t.slice(0, 90)}  <->  ${dark.trim().slice(0, 70)}`)
      if (white) sections.whiteOnOrange.push(`${rel}:${n}  bg ${t.slice(0, 90)}  <->  ${white.trim().slice(0, 70)}`)
    }
    if (hasImage && BADGE_KEY.test(line)) {
      const block = lines.slice(i, i + 12).join(" ")
      if (COLOURED_BADGE_BG.test(block.split("}")[0] ?? "")) sections.badgeOnImage.push(`${rel}:${n}  ${t.slice(0, 110)}`)
    }
    if (/(^|[^\w])(color|backgroundColor|borderColor|fg|bg|fill|stroke)\w*\s*[:=]\s*["'{]*#/i.test(line) || HEX.test(line)) {
      HEX.lastIndex = 0
      const hexes = line.match(HEX)
      if (hexes) sections.hex.push(`${rel}:${n}  ${hexes.join(" ")}`)
    }
  })
}

const out = []
const add = (title, hint, list) => {
  out.push(`## ${title} (${list.length})`, "", hint, "")
  if (!list.length) out.push("none", "")
  else out.push(...list.map((l) => `- ${l}`), "")
}
out.push("# Colour audit", "", `Generated by scripts/colorAudit.mjs over ${files.length} files.`, "")
add("Grey text (ink400 / ink300 / ink200 / #999 / #B3B3B3 as a text colour)", "Never text colours. Use textMuted / headingSecond.", sections.grey)
add("Dark text near an orange fill", "Dark text on orange is banned. Use brand (orange700) + onBrand (white).", sections.darkOnOrange)
add("White text near a mid-tone orange fill (orange300-600, gold500)", "White needs orange700/800. Bright orange500 never carries text.", sections.whiteOnOrange)
add("Coloured badge, chip or label in a file that draws images", "On a photo: dark glass + white, or white + ink800 only. Coloured chips belong on flat surfaces.", sections.badgeOnImage)
add("Hardcoded hex colours", "Use theme tokens; add a token first if one is missing.", sections.hex)

const text = out.join("\n")
const dest = process.argv[2]
if (dest) writeFileSync(dest, text)
else process.stdout.write(text)
console.error(
  `grey ${sections.grey.length} | dark-near-orange ${sections.darkOnOrange.length} | white-near-orange ${sections.whiteOnOrange.length} | badge-on-image ${sections.badgeOnImage.length} | hex ${sections.hex.length}`,
)
