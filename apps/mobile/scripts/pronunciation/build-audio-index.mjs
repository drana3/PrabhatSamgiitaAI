#!/usr/bin/env node
// Writes data/pronunciation/audioIndex.ts: for every audio id, the clip the app plays.
// Metro needs a literal require() per file, so the index is generated, not computed at run time.
// A recording in assets/audio/pronunciation/native/<audio id>.(m4a|mp3|wav) replaces the computer-voice clip of the same id.
//   node scripts/pronunciation/build-audio-index.mjs
import { existsSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { appRoot } from "./load-data.mjs"

const EXT = ["m4a", "mp3", "wav"]
const base = join(appRoot, "assets", "audio", "pronunciation")
const scan = (kind) => {
  const dir = join(base, kind)
  const out = new Map()
  if (!existsSync(dir)) return out
  for (const f of readdirSync(dir)) {
    const m = /^(.+)\.(m4a|mp3|wav)$/.exec(f)
    if (m && EXT.includes(m[2])) out.set(m[1], f)
  }
  return out
}
const computer = scan("computer")
const native = scan("native")
const ids = [...new Set([...computer.keys(), ...native.keys()])].sort()

const lines = ids.map((id) => {
  const kind = native.has(id) ? "native" : "computer"
  const file = native.get(id) ?? computer.get(id)
  return `  ${JSON.stringify(id)}: { kind: ${JSON.stringify(kind)}, source: require("../../assets/audio/pronunciation/${kind}/${file}") },`
})

const text = `// GENERATED by scripts/pronunciation/build-audio-index.mjs. Do not edit by hand.
// kind "native": a recording by a native speaker (assets/audio/pronunciation/native/).
// kind "computer": a computer-voice clip (assets/audio/pronunciation/computer/), approximate.

export type ClipKind = "computer" | "native"
export type ClipEntry = { kind: ClipKind; source: number }

export const CLIPS: Readonly<Record<string, ClipEntry>> = {
${lines.join("\n")}
}
`
writeFileSync(join(appRoot, "data", "pronunciation", "audioIndex.ts"), text)
console.log(`audioIndex.ts: ${ids.length} clips, ${native.size} native, ${ids.length - native.size} computer`)
